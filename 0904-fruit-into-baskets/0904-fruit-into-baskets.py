class Solution:
    def totalFruit(self, fruits: List[int]) -> int:
        d={}

        max_len=0

        s=0

        for f in range(len(fruits)):
            d[fruits[f]]=d.get(fruits[f],0)+1

            while len(d)>2:
                d[fruits[s]]-=1


                if d[fruits[s]]==0:
                    del d[fruits[s]]

                s+=1

            max_len=max(max_len,f-s+1)

        return max_len



























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































        